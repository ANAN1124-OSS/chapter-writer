  // 免得字表里悄悄出现「A 既转 B 又转 C」。
  function parsePairs(raw) {
    const pairs = [];
    const bad = [];
    const conflicts = [];
    const seen = new Map();
    String(raw)
      .split(/\s+/)
      .forEach((token) => {
        if (!token) return;
        if (token.length !== 2 || token[0] === token[1]) {
          bad.push(token);
          return;
        }
        const key = token[0];
        if (seen.has(key)) {
          if (seen.get(key) !== token[1]) conflicts.push(`${key}:${seen.get(key)}/${token[1]}`);
          return;
        }
        seen.set(key, token[1]);
        pairs.push(token);
      });
    return { pairs, bad, conflicts };
  }

